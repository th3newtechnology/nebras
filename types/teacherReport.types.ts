/**
 * كائنات وأنواع تقارير المعلمين التربوية والدورية
 * مدرسة نبراس القرآنية — مسجد إبراهيم الخليل
 * المرحلة الفرعية 8.4.4
 */

export type TeacherReportType = 'daily' | 'weekly' | 'monthly' | 'quarterly' | 'term';

export type TeacherReportStatus = 'draft' | 'submitted' | 'approved' | 'sent_to_guardian';

export type TeacherOverallRating = 'ممتاز' | 'جيد جداً' | 'جيد' | 'مقبول' | 'يحتاج متابعة';

export interface TeacherReport {
  id: string;
  studentId: string;
  studentName?: string;
  registrationNumber?: string;
  teacherId: string;
  teacherName?: string;
  circleId: string;
  circleName?: string;
  guardianName?: string;
  guardianPhone?: string;

  reportType: TeacherReportType;
  periodStart: string; // YYYY-MM-DD
  periodEnd: string;   // YYYY-MM-DD

  // المؤشرات الكمية والمواظبة
  attendanceRate: number;      // e.g. 100.0
  sessionsAttended: number;    // e.g. 4
  sessionsTotal: number;       // e.g. 4

  // الحفظ والمراجعة وأحكام ورش
  newMemorizationProgress: string; // e.g. "حفظ سورة النبأ من آية 1 إلى آية 20"
  revisionProgress: string;        // e.g. "مراجعة الحزب الأول من الجزء الثلاثين"
  tajweedLevel: string;            // e.g. "إتقان أحكام النون الساكنة والتنوين والمدود"
  warshAdherence: string;          // e.g. "ملتزم بمد البدل 4 حركات وتقليل ذوات الياء ونقل الهمز"

  // التقييم النوعي والتربوي
  behaviorNotes?: string;
  strengths: string;               // نقاط القوة
  areasForImprovement: string;     // نقاط التحسين وفرص التطوير
  recommendationsForGuardian: string; // توجيهات عملية لولي الأمر
  nextWeekGoals?: string;          // أهداف الأسبوع / الفترة القادمة
  overallRating: TeacherOverallRating; // التقدير العام

  // دورة الاعتماد والأمان
  status: TeacherReportStatus;
  approvedBy?: string;
  approvedByName?: string;
  approvedAt?: string;
  sentAt?: string;
  guardianViewedAt?: string;

  createdAt: string;
  updatedAt: string;
}

