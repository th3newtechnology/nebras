/**
 * استرجاع التقارير التربوية مع الفلاتر
 */
export async function fetchTeacherReports(
  filters: TeacherReportFilters = {}
): Promise<TeacherReport[]> {
  try {
    if (isSupabaseConfigured()) {
      let query = (supabase.from as any)('teacher_reports')
        .select(`
          *,
          students:student_id (full_name, registration_number, guardian_name, guardian_phone),
          teachers:teacher_id (user_id, profiles:user_id (full_name)),
          circles:circle_id (name)
        `)
        .order('created_at', { ascending: false });

      if (filters.teacherId) query = query.eq('teacher_id', filters.teacherId);
      if (filters.studentId) query = query.eq('student_id', filters.studentId);
      if (filters.circleId) query = query.eq('circle_id', filters.circleId);
      if (filters.status && filters.status !== 'all') query = query.eq('status', filters.status);
      if (filters.reportType && filters.reportType !== 'all') query = query.eq('report_type', filters.reportType);
      if (filters.periodStart) query = query.gte('period_start', filters.periodStart);
      if (filters.periodEnd) query = query.lte('period_end', filters.periodEnd);

      const { data, error } = await query;

      if (!error && data && data.length > 0) {
        return data.map((item: any) => ({
          id: item.id,
          studentId: item.student_id,
          studentName: item.students?.full_name || 'طالب مجهول',
          registrationNumber: item.students?.registration_number,
          teacherId: item.teacher_id,
          teacherName: item.teachers?.profiles?.full_name || 'الشيخ المحفظ',
          circleId: item.circle_id,
          circleName: item.circles?.name || 'الحلقة القرآنية',
          guardianName: item.students?.guardian_name,
          guardianPhone: item.students?.guardian_phone,
          reportType: item.report_type,
          periodStart: item.period_start,
          periodEnd: item.period_end,
          attendanceRate: Number(item.attendance_rate) || 0,
          sessionsAttended: item.sessions_attended || 0,
          sessionsTotal: item.sessions_total || 0,
          newMemorizationProgress: item.new_memorization_progress || '',
          revisionProgress: item.revision_progress || '',
          tajweedLevel: item.tajweed_level || '',
          warshAdherence: item.warsh_adherence || '',
          behaviorNotes: item.behavior_notes,
          strengths: item.strengths || '',
          areasForImprovement: item.areas_for_improvement || '',
          recommendationsForGuardian: item.recommendations_for_guardian || '',
          nextWeekGoals: item.next_week_goals,
          overallRating: item.overall_rating || 'ممتاز',
          status: item.status,
          approvedBy: item.approved_by,
          approvedAt: item.approved_at,
          sentAt: item.sent_at,
          guardianViewedAt: item.guardian_viewed_at,
          createdAt: item.created_at,
          updatedAt: item.updated_at,
        }));
      }
    }
  } catch (err) {
    console.warn('استخدام الذاكرة المحلية للتقارير:', err);
  }

  // فلترة الذاكرة المحلية
  let result = [...IN_MEMORY_REPORTS];

  if (filters.teacherId) {
    result = result.filter((r) => r.teacherId === filters.teacherId);
  }
  if (filters.studentId) {
    result = result.filter((r) => r.studentId === filters.studentId);
  }
  if (filters.circleId) {
    result = result.filter((r) => r.circleId === filters.circleId);
  }
  if (filters.status && filters.status !== 'all') {
    result = result.filter((r) => r.status === filters.status);
  }
  if (filters.reportType && filters.reportType !== 'all') {
    result = result.filter((r) => r.reportType === filters.reportType);
  }
  if (filters.search) {
    const s = filters.search.toLowerCase();
    result = result.filter(
      (r) =>
        r.studentName?.toLowerCase().includes(s) ||
        r.registrationNumber?.toLowerCase().includes(s) ||
        r.strengths?.toLowerCase().includes(s) ||
        r.newMemorizationProgress?.toLowerCase().includes(s)
    );
  }

  return result.sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
}

/**
 * استرجاع تقرير محدد بمعرفه
 */
export async function fetchReportById(id: string): Promise<TeacherReport | null> {
  const reports = await fetchTeacherReports();
  return reports.find((r) => r.id === id) || null;
}

