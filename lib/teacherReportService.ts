/**
 * حساب مؤشرات ملخص التقارير للمعلم أو الإدارة
 */
export async function getTeacherReportsMetrics(teacherId?: string) {
  const reports = await fetchTeacherReports({ teacherId });
  const total = reports.length;
  const drafts = reports.filter((r) => r.status === 'draft').length;
  const submitted = reports.filter((r) => r.status === 'submitted').length;
  const approved = reports.filter((r) => r.status === 'approved').length;
  const sent = reports.filter((r) => r.status === 'sent_to_guardian').length;
  const excellentCount = reports.filter((r) => r.overallRating === 'ممتاز').length;
  const excellentRate = total > 0 ? Math.round((excellentCount / total) * 100) : 0;

  return {
    total,
    drafts,
    submitted,
    approved,
    sent,
    excellentRate,
  };
}
