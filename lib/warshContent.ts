/**
 * تحويل الأرقام إلى أرقام مشرقية قرآنية
 */
export function toArabicQuranicDigits(num: number): string {
  const digits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  return num
    .toString()
    .split('')
    .map((d) => digits[parseInt(d, 10)] ?? d)
    .join('');
}

/**
 * علامة نهاية الآية برواية ورش
 */
export function formatWarshAyahBadge(ayahNumber: number): string {
  return `﴿${toArabicQuranicDigits(ayahNumber)}﴾`;
}

